/**
 * The sheet: header, then the rows newest first with the balance after each, and the summary box
 * the bank puts to the right of the first rows
 * @param {typeof PARSIAN_SAMPLE} [sample]
 * @param {number} [opening] balance before the first row, in rials
 */
export function parsianSheet(sample = PARSIAN_SAMPLE, opening = 10_000_000_000) {
  let balance = opening;
  const body = sample.map(([date, time, description, word, amount], i) => {
    balance += word === 'واریز' ? amount : -amount;
    return { i, date, time, description, word, amount, balance };
  }).reverse();
  const summary = [
    ['موجودی (ریال)', group(balance)],
    ['واریز (ریال)', '+ 1'],
    ['برداشت (ریال)', '- -1'],
    ['ناریخ', '1405/05/01 - 1405/05/22'],
  ];
  const rows = [['ردیف', 'تاریخ', 'توضیحات', 'واریز/ برداشت', 'مبلغ (ریال)', 'موجودی(ریال)', 'شرح', null, null, summary[0][0], summary[0][1]]];
  body.forEach((r, n) => {
    const sign = r.word === 'واریز' ? '+' : '-';
    rows.push([
      String(n + 1), `${r.date} - ${r.time}`, r.description, r.word, `${sign} ${group(r.amount)}`, group(r.balance), '',
      null, null, summary[n + 1]?.[0] ?? null, summary[n + 1]?.[1] ?? null,
    ]);
  });
  return rows;
}
